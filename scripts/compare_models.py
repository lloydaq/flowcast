"""Side-by-side comparison of every model, with uncertainty on the LightGBM vs DCRNN gap.

Usage:  python scripts/compare_models.py   (after run_baselines, train_lightgbm and train_dcrnn)

Writes docs/model_comparison.md (generated: do not edit) and models/metrics/comparison.json.

The headline numbers come from each model's metrics JSON. The gap between the two learned models is
also re-computed from their saved predictions on the same rows, with a 95% interval from a block
bootstrap over days: errors within a day are strongly correlated (one jam affects many rows), so
days, not rows, are the independent units. Rows are resampled as whole days, 2,000 times.
"""

from __future__ import annotations

import json

import numpy as np
import pandas as pd

from flowcast import paths
from flowcast.data.processed import load_speed
from flowcast.evaluation.results import SPLITS, load_results
from flowcast.evaluation.rows import load_eval_rows
from flowcast.features.build import HORIZONS
from flowcast.reporting import print_report

ROOT = paths.PROJECT_ROOT
METRICS = paths.METRICS_DIR
PREDICTIONS = paths.PREDICTIONS_DIR
OUT_MD = ROOT / "docs" / "model_comparison.md"
OUT_JSON = METRICS / "comparison.json"
N_BOOT, SEED = 2000, 0


def bootstrap_gap(speed: pd.DataFrame) -> dict:
    """MAE(DCRNN) - MAE(LightGBM) per split and horizon, with a day-block bootstrap 95% interval."""
    rng = np.random.default_rng(SEED)
    out: dict = {}
    for split in SPLITS:
        rows = load_eval_rows(split, speed)
        lgb = pd.read_parquet(PREDICTIONS / f"lightgbm_{split}.parquet")
        dcr = pd.read_parquet(PREDICTIONS / f"dcrnn_{split}.parquet")
        for other in (lgb, dcr):
            same = (other["timestamp"].to_numpy() == rows.frame["timestamp"].to_numpy()).all() and (
                other["node_id"].to_numpy() == rows.node
            ).all()
            if not same:
                raise ValueError(f"{split}: prediction rows differ from the evaluation rows")
        day = pd.DatetimeIndex(rows.frame["timestamp"]).normalize()
        day_codes, days = pd.factorize(day)
        out[split] = {}
        for h in HORIZONS:
            y = rows.target(h)
            ok = ~np.isnan(y)
            e_l = np.abs(lgb[f"pred_h{h}"].to_numpy(np.float64) - y)
            e_d = np.abs(dcr[f"pred_h{h}"].to_numpy(np.float64) - y)
            codes = day_codes[ok]
            n = np.bincount(codes, minlength=len(days)).astype(np.float64)
            s_l = np.bincount(codes, e_l[ok], minlength=len(days))
            s_d = np.bincount(codes, e_d[ok], minlength=len(days))
            draws = rng.integers(0, len(days), (N_BOOT, len(days)))
            gaps = (s_d[draws].sum(1) - s_l[draws].sum(1)) / n[draws].sum(1)
            gap = (s_d.sum() - s_l.sum()) / n.sum()
            lo, hi = np.percentile(gaps, [2.5, 97.5])
            out[split][f"h{h}"] = {
                "mae_gap": round(float(gap), 4),
                "ci95": [round(float(lo), 4), round(float(hi), 4)],
                "days": len(days),
                "days_dcrnn_better": int((s_d / np.maximum(n, 1) < s_l / np.maximum(n, 1)).sum()),
            }
    return out


def verdict(g: dict) -> str:
    lo, hi = g["ci95"]
    if hi < 0:
        return "DCRNN better"
    if lo > 0:
        return "LightGBM better"
    return "no clear difference"


def render(models: dict, gap: dict) -> str:
    lines = [
        "# Model comparison",
        "",
        "Generated by `scripts/compare_models.py` from `models/metrics/*.json` and the saved predictions. "
        "Do not edit by hand.",
        "",
        "Every model is scored on the same rows (the feature-table rows of each split) with the same masked "
        "metrics. Validation chose LightGBM's settings and stopped both learned models' training, so "
        "validation numbers for them are slightly optimistic; test was scored once per model.",
        "",
    ]
    for split in SPLITS:
        lines += [f"## {split.capitalize()}: MAE / RMSE (mph)", ""]
        lines += ["| Model | " + " | ".join(f"{h * 5} min" for h in HORIZONS) + " |"]
        lines += ["|---|" + "---:|" * len(HORIZONS)]
        best = {h: min(models, key=lambda m, h=h: models[m][split][f"h{h}"]["all"]["mae"]) for h in HORIZONS}
        for name, res in models.items():
            cells = []
            for h in HORIZONS:
                a = res[split][f"h{h}"]["all"]
                cell = f"{a['mae']:.2f} / {a['rmse']:.2f}"
                cells.append(f"**{cell}**" if best[h] == name else cell)
            lines.append(f"| {name} | " + " | ".join(cells) + " |")
        lines.append("")

    lines += [
        "## Validation MAE by slice",
        "",
        "| Model | Horizon | peak | off-peak | congested | free-flowing |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for name in ("AR on residuals", "LightGBM", "DCRNN"):
        for h in HORIZONS:
            r = models[name]["validation"][f"h{h}"]
            cells = " | ".join(
                f"{r[s]['mae']:.2f}" for s in ("peak", "off_peak", "congested", "free_flowing")
            )
            lines.append(f"| {name} | {h * 5} min | {cells} |")
    lines += [
        "",
        "## Is DCRNN really different from LightGBM?",
        "",
        "MAE(DCRNN) − MAE(LightGBM) in mph; negative means DCRNN is better. The interval is a 95% "
        f"day-block bootstrap ({N_BOOT:,} resamples). A difference counts only when the interval excludes 0.",
        "",
        "| Split | Horizon | Gap | 95% interval | Days DCRNN better | Verdict |",
        "|---|---|---:|---|---:|---|",
    ]
    for split in SPLITS:
        for h in HORIZONS:
            g = gap[split][f"h{h}"]
            lines.append(
                f"| {split} | {h * 5} min | {g['mae_gap']:+.3f} | [{g['ci95'][0]:+.3f}, {g['ci95'][1]:+.3f}] "
                f"| {g['days_dcrnn_better']} of {g['days']} | {verdict(g)} |"
            )
    lines += [
        "",
        "Caveat: the interval covers day-to-day variation in the data, not training randomness. Each learned "
        "model was trained once with one seed.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    models = load_results()
    gap = bootstrap_gap(load_speed())
    OUT_JSON.write_text(json.dumps({"mae_gap_dcrnn_minus_lightgbm": gap}, indent=1), encoding="utf-8")
    OUT_MD.write_text(render(models, gap), encoding="utf-8")
    print_report(OUT_MD)


if __name__ == "__main__":
    main()
