"""Score the baselines on validation and test.

Usage:  python scripts/run_baselines.py   (after scripts/build_features.py)

Writes models/metrics/baselines.json and docs/baseline_results.md (generated: do not edit).
Every fitted part (historical profile, AR coefficients, free-flow speed) uses the training
period only. Baselines have no hyperparameters tuned on validation, so the test score is a
single honest floor for later models, computed here and not looked at again until Phase 5's test run.
"""

from __future__ import annotations

import json
import time

import numpy as np

from flowcast import paths
from flowcast.data.processed import load_speed, owned_period
from flowcast.evaluation.metrics import MAPE_MIN_SPEED, PEAK_HOURS
from flowcast.evaluation.rows import load_eval_rows
from flowcast.features.build import HORIZONS, row_times
from flowcast.models.baselines import ARResidual, HistoricalAverage, Persistence, SeasonalNaive
from flowcast.reporting import print_report

METRICS_PATH = paths.PROJECT_ROOT / "models" / "metrics" / "baselines.json"
REPORT_PATH = paths.PROJECT_ROOT / "docs" / "baseline_results.md"
SPLITS = ("validation", "test")
SLICES = ("all", "peak", "off_peak", "congested", "free_flowing")


def main() -> None:
    started = time.perf_counter()
    speed = load_speed()
    ha = HistoricalAverage().fit(load_speed("train"))
    train_times = row_times(speed.index, owned_period("train"))
    models = [
        Persistence(ha),
        ha,
        SeasonalNaive(ha),
        ARResidual(ha).fit(speed, train_times, HORIZONS),
    ]

    rows = {split: load_eval_rows(split, speed) for split in SPLITS}
    results: dict = {name: {} for name in SPLITS}
    for model in models:
        for h in HORIZONS:
            pred = model.predict(speed, h)
            fallback = model.fallback_mask(speed, h) if hasattr(model, "fallback_mask") else None
            for split, r in rows.items():
                scores = r.score(pred, h)
                has = ~np.isnan(r.target(h))
                scores["fallback_pct"] = (
                    0.0 if fallback is None else float(fallback[r.t_idx, r.node][has].mean() * 100)
                )
                results[split].setdefault(model.name, {})[f"h{h}"] = scores

    payload = {
        "definitions": {
            "metrics": "masked: rows with a missing target are excluded",
            "mape_min_speed_mph": MAPE_MIN_SPEED,
            "peak": f"weekday target time in hours {list(PEAK_HOURS)} ([start, end))",
            "congested": "target < 0.6 x sensor free-flow (train p85)",
            "horizons_minutes": {f"h{h}": h * 5 for h in HORIZONS},
            "fit_period": "train owned period",
        },
        "results": results,
        "runtime_s": round(time.perf_counter() - started, 1),
    }
    METRICS_PATH.parent.mkdir(parents=True, exist_ok=True)
    METRICS_PATH.write_text(json.dumps(payload, indent=1), encoding="utf-8")
    REPORT_PATH.write_text(render(results), encoding="utf-8")
    print_report(REPORT_PATH)
    print(f"runtime {payload['runtime_s']} s")


def render(results: dict) -> str:
    out = [
        "# Baseline results",
        "",
        "Generated by `scripts/run_baselines.py` from `models/metrics/baselines.json`. Do not edit by hand.",
        f"MAE and RMSE in mph; MAPE in %, excluding targets under {MAPE_MIN_SPEED:g} mph.",
        "",
    ]
    for split in SPLITS:
        out += [
            f"## {split.capitalize()}",
            "",
            "| Baseline | " + " | ".join(f"{h * 5} min MAE / RMSE / MAPE" for h in HORIZONS) + " |",
            "|---|" + "---:|" * len(HORIZONS),
        ]
        for name, by_h in results[split].items():
            cells = [
                f"{m['mae']:.2f} / {m['rmse']:.2f} / {m['mape']:.1f}%"
                for m in (by_h[f"h{h}"]["all"] for h in HORIZONS)
            ]
            out.append(f"| {name} | " + " | ".join(cells) + " |")
        out += [
            "",
            f"MAE by slice at 60 min ({split}):",
            "",
            "| Baseline | " + " | ".join(SLICES) + " | fallback % |",
            "|---|" + "---:|" * (len(SLICES) + 1),
        ]
        for name, by_h in results[split].items():
            r = by_h[f"h{HORIZONS[-1]}"]
            out.append(
                f"| {name} | "
                + " | ".join(f"{r[s]['mae']:.2f}" for s in SLICES)
                + f" | {r['fallback_pct']:.1f} |"
            )
        n = results[split][next(iter(results[split]))]
        out += [
            "",
            "Rows scored (60 min): " + ", ".join(f"{s} {n[f'h{HORIZONS[-1]}'][s]['n']:,}" for s in SLICES),
            "",
        ]
    return "\n".join(out)


if __name__ == "__main__":
    main()
